"""
knock41.py: 少样本推理 / Few-Shot推論
通过提供多个学习样本来引导模型的推理方法。 / 複数の学習例を与えてモデルの推論方法を誘導します。
在问题40的基础上添加解答示例。 / 問題40に解答例を追加します。

"""

from openai_config import DEFAULT_MAX_COMPLETION_TOKENS, DEFAULT_MODEL, create_openai_client  # 导入配置常量和OpenAI客户端创建函数 / 設定定数とOpenAIクライアント作成関数をインポート


def few_shot_reasoning():  # 定义少样本推理函数 / Few-shot推論関数を定義
    client = create_openai_client()  # 初始化OpenAI客户端 / OpenAIクライアントを初期化

    prompt = (  # 构建包含少样本示例的提示词 / Few-shot例を含むプロンプトを構築
        """
    下面提供问题和解答示例作为参考，然后回答最后的问题 / 以下の問題と解答例を参考にして、最後の問題に答えてください

    【示例1】与日本现代化相关的事件 / 【例1】日本の近代化に関するできごと
    ア　府知事・県令からなる地方官会議が設置された。
    イ　廃藩置県が実施され，中央から府知事・県令が派遣される体制になった。
    ウ　すべての藩主が，天皇に領地と領民を返還した。
    解答: ウ→イ→ア

    【示例2】江户幕府北方的对外紧张局势 / 【例2】江戸幕府北方の対外緊張に関するできごと
    ア　レザノフが長崎に来航したが，幕府が冷淡な対応をしたため，ロシア船が樺太や択捉島を攻撃した。
    イ　ゴローウニンが国後島に上陸し，幕府の役人に捕らえられ抑留された。
    ウ　ラクスマンが根室に来航し，漂流民を届けるとともに通商を求めた。
    解答: ウ→ア→イ

    【示例3】中居屋重兵衛生涯期间发生的事件 / 【例3】中居屋重兵衛の生涯期間に起きたできごと
    ア　アヘン戦争がおこり，清がイギリスに敗北した。
    イ　異国船打払令が出され，外国船を撃退することが命じられた。
    ウ　桜田門外の変がおこり，大老の井伊直弼が暗殺された。
    解答: イ→ア→ウ

    【示例4】与加藤高明相关的事件 / 【例4】加藤高明に関するできごと
    ア　朝鮮半島において，独立を求める大衆運動である三・一独立運動が展開された。
    イ　関東大震災後の混乱のなかで，朝鮮人や中国人に対する殺傷事件がおきた。
    ウ　日本政府が，袁世凱政府に対して二十一カ条の要求を突き付けた。
    解答: ウ→ア→イ

    【问题】9世纪活跃的人物相关事件 / 【問題】9世紀に活躍した人物に関するできごと
    ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。
    イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。
    ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。

    按照上述示例的格式回答。 / 上記の例と同じ形式で答えてください。
    仅输出答案，格式为「ア→イ→ウ」的形式，一行输出。 / 解答のみを「ア→イ→ウ」の形式で1行で出力してください。
    """
    )

    message = client.chat.completions.create(  # 调用OpenAI API发送提示词 / OpenAI APIにプロンプトを送信
        model=DEFAULT_MODEL,  # 指定使用的模型 / 使用するモデルを指定
        max_completion_tokens=DEFAULT_MAX_COMPLETION_TOKENS,  # 设置最大完成token数 / 最大補完トークン数を設定
        reasoning_effort="minimal",  # 设置推理难度为最小 / 推論の負荷を最小に設定
        verbosity="low",  # 设置详细度为低 / 出力の詳細度を低く設定
        messages=[  # 构建消息列表 / メッセージリストを構築
            {
                "role": "user",  # 消息角色为用户 / メッセージの役割をユーザーに設定
                "content": prompt,  # 消息内容为包含示例和问题的提示词 / 例と問題を含むプロンプトをメッセージ内容に設定
            }
        ]
    )

    print("=" * 60)  # 输出分割线 / 区切り線を出力
    print("knock41: Few-Shot推論（4-shot推論）")  # 输出任务标题 / タスクのタイトルを出力
    print("=" * 60)  # 输出分割线 / 区切り線を出力
    print("\n【解答】")  # 输出答案标签 / 解答ラベルを出力
    answer = message.choices[0].message.content or ""  # 从API响应中提取答案或空字符串 / API応答から解答を取り出し、空なら空文字列にする
    print(answer)  # 输出答案 / 解答を出力
    if not answer.strip():
        print("\n【デバッグ】")  # 输出调试标签 / デバッグラベルを出力
        print(f"finish_reason: {message.choices[0].finish_reason}")  # 输出生成完成原因 / 生成終了理由を出力
        print(f"usage: {message.usage}")  # 输出API使用信息 / API使用量情報を出力
    print("\n" + "=" * 60)  # 输出分割线 / 区切り線を出力

    return answer  # 返回模型的答案 / モデルの解答を返す


if __name__ == "__main__":
    few_shot_reasoning()

