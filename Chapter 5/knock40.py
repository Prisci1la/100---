"""
knock40.py: 零样本推理 / Zero-Shot推論

不提供额外学习样本，直接生成问题答案。 / 追加の学習例を与えずに、直接問題の解答を生成します。

问题：将9世纪日本史相关事件按年代排序 / 問題: 9世紀の日本史に関するできごとを年代順に並べる
"""

from openai_config import DEFAULT_MAX_COMPLETION_TOKENS, DEFAULT_MODEL, create_openai_client  # 导入配置常量和OpenAI客户端创建函数 / 設定定数とOpenAIクライアント作成関数をインポート


def zero_shot_reasoning():  # 用零样本推理求解历史问题 / Zero-shot推論で歴史問題を解く
    client = create_openai_client()  # 初始化OpenAI客户端 / OpenAIクライアントを初期化

    question = (  # 定义待解决的多选题问题 / 解く多肢選択問題を定義
        """
    9世紀に活躍した人物に関係するできごとについて述べた次のア～ウを年代の古い順に正しく並べよ。

    ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。
    イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。
    ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。

    答えは、ア、イ、ウのいずれかの組み合わせで、年代の古い順に答えてください。
    解答のみを「ア→イ→ウ」のような形式で1行で出力してください。
    """
    )

    message = client.chat.completions.create(  # 调用OpenAI API发送问题 / OpenAI APIに質問を送信
        model=DEFAULT_MODEL,  # 指定使用的GPT模型 / 使用するGPTモデルを指定
        max_completion_tokens=DEFAULT_MAX_COMPLETION_TOKENS,  # 设置最大完成token数 / 最大補完トークン数を設定
        reasoning_effort="minimal",  # 设置推理难度为最小 / 推論の負荷を最小に設定
        verbosity="low",  # 设置详细度为低 / 出力の詳細度を低く設定
        messages=[  # 构建消息列表 / メッセージリストを構築
            {
                "role": "user",  # 消息角色为用户 / メッセージの役割をユーザーに設定
                "content": question,  # 消息内容为历史问题 / メッセージ内容を歴史問題に設定
            }
        ]
    )

    print("=" * 60)  # 显示结果并输出分割线 / 結果表示を開始し、区切り線を出力
    print("knock40: Zero-Shot推論")  # 输出任务标题 / タスクのタイトルを出力
    print("=" * 60)  # 输出分割线 / 区切り線を出力
    print("\n【問題】")  # 输出问题标签 / 問題ラベルを出力
    print(question)  # 输出问题内容 / 問題文を出力
    print("\n【解答】")  # 输出答案标签 / 解答ラベルを出力
    print(message.choices[0].message.content)  # 从API响应中提取并输出答案 / API応答から解答を取り出して出力
    print("\n" + "=" * 60)  # 输出分割线 / 区切り線を出力

    return message.choices[0].message.content  # 返回模型的答案 / モデルの解答を返す


if __name__ == "__main__":
    zero_shot_reasoning()

