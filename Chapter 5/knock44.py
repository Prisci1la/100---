"""
knock44.py: 对话 / 対話
通过单一回合的对话回答复杂问题。 / 単一ターンの対話で複雑な問題に回答します。
问题：关于东京电车换乘的推理问题。 / 問題: 東京の電車乗り換えに関する推論問題です。
"""

from openai_config import DEFAULT_MAX_COMPLETION_TOKENS, DEFAULT_MODEL, create_openai_client  # 导入配置常量和OpenAI客户端 / 設定定数とOpenAIクライアントをインポート


def single_turn_dialogue():  # 执行单回合对话 / 単一ターン対話を実行する

    client = create_openai_client()  # 初始化OpenAI客户端 / OpenAIクライアントを初期化

    question = (  # 定义问题内容 / 問題内容を定義
        """
    小燕子从渋谷站乘坐东急东横线，在自由丘站换乘。 / つばめちゃんは渋谷駅から東急東横線に乗り、自由が丘駅で乗り換えました。
    换乘到东急大井町线大井町方向电车时， / 東急大井町線の大井町方面の電車に乗り換えたとき、
    本应乘坐各站停车电车，却误乘急行后才意识到。 / 各駅停車に乗るべきところ、間違えて急行に乗車したことに気付きました。
    在自由丘的下一个急行停靠站下车， / 自由が丘の次の急行停車駅で降車し、
    再乘坐反方向电车返回一站，到达的车站就是小燕子的目的地。 / 反対方向の電車で一駅戻った駅がつばめちゃんの目的地でした。
    请回答目的地车站的名称。 / 目的地の駅名を答えてください。
    """
    )

    message = client.chat.completions.create(  # 调用OpenAI API生成回答 / OpenAI APIを呼び出して回答を生成
        model=DEFAULT_MODEL,  # 指定模型 / モデルを指定
        max_completion_tokens=DEFAULT_MAX_COMPLETION_TOKENS,  # 设置最大token数 / 最大トークン数を設定
        reasoning_effort="minimal",  # 设置推理难度为最小 / 推論の負荷を最小に設定
        verbosity="low",  # 设置详细度为低 / 出力の詳細度を低く設定
        messages=[  # 构建消息列表 / メッセージリストを構築
            {
                "role": "user",  # 消息角色为用户 / メッセージの役割をユーザーに設定
                "content": question,  # 消息内容为问题 / メッセージ内容を問題に設定
            }
        ]
    )

    response = message.choices[0].message.content or ""  # 从API响应中提取回答文本 / API応答から回答文を抽出

    print("=" * 60)  # 输出分割线 / 区切り線を出力
    print("knock44: 対話（単一ターン）")  # 输出任务标题 / タスクのタイトルを出力
    print("=" * 60)  # 输出分割线 / 区切り線を出力
    print("\n【質問】")  # 输出问题标签 / 質問ラベルを出力
    print(question)  # 输出问题内容 / 質問内容を出力
    print("\n【回答】")  # 输出回答标签 / 回答ラベルを出力
    print(response)  # 输出模型的回答 / モデルの回答を出力
    print("\n" + "=" * 60)  # 输出分割线 / 区切り線を出力

    return response  # 返回模型的回答 / モデルの回答を返す


if __name__ == "__main__":
    single_turn_dialogue()

