"""
23. セクション構造 / 章节结构
記事中に含まれるセクション名とそのレベルを表示する。
显示文章中包含的章节名及其级别。

MediaWiki のセクション記法 / MediaWiki 的章节标记：
  == セクション ==     → レベル 1 / 级别 1
  === セクション ===   → レベル 2 / 级别 2
  ==== セクション ==== → レベル 3 / 级别 3
（イコール数 - 1 がレベル / 等号数 - 1 即为级别）
"""

import re
from knock20 import load_uk_article


def extract_sections(text: str) -> list[tuple[str, int]]:
    """
    (セクション名, レベル) のタプルのリストを返す。
    返回 (章节名, 级别) 元组组成的列表。
    """
    # 行頭の == ... == 形式にマッチ / 匹配行首的 == ... == 形式
    # ^(={2,})\s*(.+?)\s*\1$  両側のイコール数が同じでなければならない / 两侧等号数必须相同
    pattern = re.compile(r"^(={2,})\s*(.+?)\s*\1\s*$", re.MULTILINE)

#^ — 行の始まり
#(={2,}) — == または === などの = を捕捉（グループ 1）
#\s* — その後ろにスペースがあるかもしれない
#(.+?) — 見出しのテキストを捕捉（グループ 2）
#\s* — その後ろにスペースがあるかもしれない
#\1 — グループ 1 と同じ数の = が出てくること（\1 はバックリファレン#ス）
#\s* — 最後にスペースがあるかもしれない
#$ — 行の終わり

    result = []
    for match in pattern.finditer(text):
        equals = match.group(1)   # = の連続 / 等号串
        name = match.group(2)     # セクション名 / 章节名
        level = len(equals) - 1   # レベル計算 / 计算级别
        result.append((name, level))
    return result


if __name__ == "__main__":
    # 本文取得 / 取得正文
    text = load_uk_article()

    # セクション抽出 / 提取章节
    sections = extract_sections(text)

    # 表示 / 输出
    for name, level in sections:
        print(f"{name}\t{level}")

